"""Independent, bounded aggregation of already accepted single-event Alerts.

Import AlertAggregator from this module to use it independently of AlertManager.
Callers must consume result.finalized and flush() output: no closed history is
retained internally. All output and input evidence is detached from live state.
"""

from copy import deepcopy
from dataclasses import dataclass, replace
import math
from typing import Literal
from uuid import uuid4

from .aggregation_config import AggregationConfig
from .models import Alert, AlertGroup


@dataclass(frozen=True, slots=True)
class AggregationResult:
    status: Literal["created", "merged", "late", "bypassed"]
    group: AlertGroup
    finalized: tuple[AlertGroup, ...] = ()


class AggregationCapacityError(RuntimeError):
    """Capacity reached; state is unchanged. Consume flush() and retry input."""


class AlertAggregator:
    """Fixed inclusive event-time windows keyed by (sid, src_ip, dst_ip).

    process() expires ALL keys against a monotonic event-time watermark, then
    merges into an eligible open group. Late input may still join an open
    window; otherwise it is returned as a finalized singleton, never reopening
    closed groups or shifting first_seen. No wall-clock time is consulted.

    max_groups and max_events_per_group bound retained state without silently
    dropping evidence or splitting an in-window group. Capacity errors are
    atomic; the caller can flush and retry, or stop and persist the input.
    This engine is single-threaded and expects normalized, accepted Alerts
    with count=1 and unique source IDs (normally generated by AlertManager).
    """

    def __init__(
        self,
        config: AggregationConfig | None = None,
        *,
        max_groups: int = 1024,
        max_events_per_group: int = 1000,
    ) -> None:
        config = config if config is not None else AggregationConfig()
        if not isinstance(config, AggregationConfig):
            raise TypeError("Expected AggregationConfig")
        for name, value in (("max_groups", max_groups),
                            ("max_events_per_group", max_events_per_group)):
            if type(value) is not int or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        self._config = config
        self._max_groups = max_groups
        self._max_events_per_group = max_events_per_group
        self._groups: dict[tuple[int, str, str], AlertGroup] = {}
        self._watermark: float | None = None

    @property
    def config(self) -> AggregationConfig:
        return self._config

    @property
    def active_group_count(self) -> int:
        return len(self._groups)

    @staticmethod
    def _key(alert: Alert) -> tuple[int, str, str]:
        return alert.sid, alert.src_ip, alert.dst_ip

    def process(self, alert: Alert) -> AggregationResult:
        """Return a detached current snapshot and every group closed this call.

        A late/bypassed group's snapshot is also in finalized; consumers should
        persist finalized only, using group as a provisional view otherwise.
        Invalid input and capacity failures leave state and watermark unchanged.
        """
        if not isinstance(alert, Alert):
            raise TypeError("Expected Alert, not an AlertResult or detection dictionary")
        if type(alert.count) is not int or alert.count != 1:
            raise ValueError("Expected a single-event Alert with count=1")
        timestamp = alert.timestamp
        if type(timestamp) not in (int, float):
            raise ValueError("timestamp must be finite non-negative seconds")
        try:
            timestamp = float(timestamp)
        except OverflowError as exc:
            raise ValueError("timestamp is outside the supported range") from exc
        if not math.isfinite(timestamp) or timestamp < 0:
            raise ValueError("timestamp must be finite non-negative seconds")

        source = deepcopy(alert)
        summary = replace(source, timestamp=timestamp, first_seen=timestamp,
                          last_seen=timestamp, count=1)
        singleton = AlertGroup(summary, (source,))
        if not self.config.enabled:
            return deepcopy(AggregationResult("bypassed", singleton, (singleton,)))

        watermark = timestamp if self._watermark is None else max(timestamp, self._watermark)
        window = self.config.window_seconds
        expired = tuple(key for key, group in self._groups.items()
                        if watermark - group.summary.first_seen > window)
        key = self._key(source)
        current = None if key in expired else self._groups.get(key)
        inside = (current is not None and
                  0 <= timestamp - current.summary.first_seen <= window)
        late = not inside and timestamp < watermark

        if inside and current.summary.count >= self._max_events_per_group:
            raise AggregationCapacityError("max_events_per_group reached; flush and retry")
        if not inside and not late and len(self._groups) - len(expired) >= self._max_groups:
            raise AggregationCapacityError("max_groups reached; flush and retry")

        if inside:
            group = AlertGroup(
                replace(current.summary, count=current.summary.count + 1,
                        last_seen=max(current.summary.last_seen, timestamp)),
                current.members + (source,),
            )
            status = "merged"
        else:
            # Reused input IDs must not identify both a closing/open group and
            # its replacement within this transition. Original ID stays in members.
            if any(g.summary.alert_id == summary.alert_id for g in self._groups.values()):
                singleton = replace(singleton, summary=replace(summary, alert_id=str(uuid4())))
            group = singleton
            status = "late" if late else "created"

        finalized = tuple(self._groups[k] for k in expired)
        if late:
            finalized += (group,)
        # Copy before committing state so an output snapshot never aliases it.
        result = deepcopy(AggregationResult(status, group, finalized))
        for expired_key in expired:
            del self._groups[expired_key]
        if not late:
            self._groups[key] = group
        self._watermark = watermark
        return result

    def flush(self) -> tuple[AlertGroup, ...]:
        """Finalize and remove all open groups; repeated flush returns ().

        Keep the event-time watermark: subsequent older input remains late.
        Create a new aggregator for an unrelated stream/time domain. The caller
        owns delivery/persistence of returned groups; there is no durable queue.
        """
        finalized = deepcopy(tuple(self._groups.values()))
        self._groups.clear()
        return finalized
